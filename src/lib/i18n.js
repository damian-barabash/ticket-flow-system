function walk(tree, path) {
  return path.split('.').reduce((acc, k) => (acc == null ? acc : acc[k]), tree)
}

function interpolate(str, vars) {
  if (!vars || typeof str !== 'string') return str
  return str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
}

// translate(lang, 'login.submit', { n: 3 }) → localized string (falls back to ru, then the key).
export function translate(lang, key, vars) {
  const l = normalizeLang(lang)
  // 1.1 feature strings (chat, calendar, assignee, notifications, reset) first
  let val = walk(FEATURES[l], key)
  if (val == null) val = walk(PANEL[l], key)
  if (val == null) val = walk(DICT[l], key)
  if (val == null) val = walk(FEATURES[DEFAULT_LANG], key)
  if (val == null) val = walk(PANEL[DEFAULT_LANG], key)
  if (val == null) val = walk(DICT[DEFAULT_LANG], key)
  if (val == null) return key
  return interpolate(val, vars)
}

// Raw tree access (arrays like months/units, nested enum objects).
export function dict(lang) {
  return DICT[normalizeLang(lang)]
}

// Bind a translator to a fixed language.
export function makeT(lang) {
  return (key, vars) => translate(lang, key, vars)
}
